"""Build orchestration: scan archives → load → analyse → render → write.

The writer is deliberately timid. memloom owns only the files it generated (they carry
a ``generated by memloom`` comment), so pointing it at an existing Obsidian vault is
safe: your own notes survive, stale memloom pages get cleaned up.
"""

from __future__ import annotations

import os
import time
from typing import Dict, List, Optional, Sequence, Set, Tuple

from .adapters import all_default_roots, detect_adapter, get_adapter
from .group import SessionFacts, analyze, group_projects, group_topics
from .model import Session
from .state import Cache
from .render import (
    DIR_ARCHIVE,
    DIR_PROJECT,
    DIR_SESSION,
    DIR_TOPIC,
    GENERATED_MARK,
    GUIDE_NAME,
    INDEX_NAME,
    render_archive_note,
    render_guide,
    render_index,
    render_project,
    render_session,
    render_topic,
    session_page_name,
    topic_page_name,
)
from .util import ensure_dir, settle, sha1, within_days

DEFAULT_TITLE = "记忆库"
DEFAULT_SOURCE = "memloom"
DEFAULT_PREFIX = "memloom"


# ------------------------------------------------------------------ scan

def scan(roots: Optional[Sequence[Tuple[str, str]]] = None,
         only: Optional[str] = None) -> List[Tuple[str, str]]:
    """Return ``[(adapter_name, path)]`` for every archive worth reading.

    ``roots`` defaults to each adapter's standard location. ``only`` restricts the scan
    to one adapter (``"dsh"`` / ``"claude-code"`` / ``"codex"`` / ``"antigravity"``).
    """
    pairs: List[Tuple[str, str]] = []
    for name, root in roots or all_default_roots():
        if only and name != only:
            continue
        if not root or not os.path.isdir(root):
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in ("node_modules", ".git")]
            for fn in filenames:
                path = os.path.join(dirpath, fn)
                try:
                    if os.path.getsize(path) < 64:
                        continue
                except OSError:
                    continue
                adapter = detect_adapter(path)
                if adapter is None:
                    continue
                if only and adapter.name != only:
                    continue
                pairs.append((adapter.name, path))
    pairs.sort(key=lambda x: x[1])
    return pairs


def load_all(pairs: Sequence[Tuple[str, str]], quiet: bool = False,
             cache: Optional[Cache] = None,
             verbose: bool = False) -> Tuple[Dict[str, Session], List[str]]:
    """Parse every archive; returns ``(sessions_by_id, problems)``.

    With a ``cache``, files whose size/mtime are unchanged are restored from disk instead
    of being parsed again -- zstd decompression is the expensive part of a build.

    Only files that were actually parsed are echoed. A rebuild where nothing changed
    therefore prints no per-file lines at all, which is how you can tell the cache
    worked without reading the counters. ``verbose`` echoes cache hits too.
    """
    sessions: Dict[str, Session] = {}
    problems: List[str] = []
    for name, path in pairs:
        adapter = get_adapter(name)
        if adapter is None:
            problems.append(f"{path}: 未知适配器 {name}")
            continue
        s: Optional[Session] = cache.lookup(path, name) if cache is not None else None
        from_cache = s is not None
        if s is None:
            try:
                s = adapter.load(path)
            except Exception as exc:  # a broken file must never abort the whole build
                problems.append(f"{path}: {type(exc).__name__}: {exc}")
                continue
            if s is not None and not s.is_empty():
                if cache is not None:
                    cache.store(path, name, s)
        if s is None or s.is_empty():
            problems.append(f"{path}: 没有可读的对话内容")
            continue
        if s.id in sessions:
            old = sessions[s.id]
            if len(s.turns) > len(old.turns):
                sessions[s.id] = s
            continue
        sessions[s.id] = s
        if not quiet and (verbose or not from_cache):
            mark = "·" if from_cache else "+"
            print(f"  {mark} {os.path.basename(path)}  {len(s.turns)} 轮 / {s.n_tools} 工具", flush=True)
    return sessions, problems


# ------------------------------------------------------------------ writing


def settle_titles(sessions: Dict[str, "Session"]) -> None:
    """Repair titles the source archive already broke.

    Runs before ``number_duplicate_titles`` on purpose: the 「· 02」 suffix must
    land on a cleaned title, otherwise the ordinal gets glued to a dangling
    bracket and the page reads ``…DSH(De · 04``.
    """
    for s in sessions.values():
        fixed = settle(s.title or "")
        if fixed:
            s.title = fixed


def number_duplicate_titles(sessions: Dict[str, "Session"]) -> None:
    """Give same-title sessions on the same day a 「· 02」 suffix, in run order.

    A scheduled run and its next run carry the same title by design, so inside one
    date the only thing that tells them apart is which came first. Numbering them
    keeps every page name unique without inventing a title the archive never had.
    Sessions with a unique title on that date are left untouched.
    """
    groups: Dict[Tuple[str, str], List["Session"]] = {}
    for s in sessions.values():
        groups.setdefault((s.title or "", s.date), []).append(s)
    for items in groups.values():
        if len(items) < 2:
            continue
        items.sort(key=lambda s: (s.started_at.timestamp() if s.started_at else 0.0, s.id))
        for i, s in enumerate(items, 1):
            s.title = f"{s.title} · {i:02d}"


def _uniq_page_names(pages: Sequence[Tuple[str, str]]) -> List[Tuple[str, str]]:
    """Two pages must never share one path -- the second would silently overwrite the first.

    Generated names come from truncated titles, so unrelated topics can collide
    (``踩坑-Failed to authenticate….md``). Kept pages without a conflict keep their name;
    a colliding page gets a short content hash appended; an identical duplicate is dropped.
    """
    originals = {rel for rel, _ in pages}
    taken: Dict[str, str] = {}
    out: List[Tuple[str, str]] = []
    for rel, text in pages:
        if rel in taken:
            if taken[rel] == text:
                continue
            stem, ext = os.path.splitext(rel)
            for width in (4, 6, 8, 12):
                cand = f"{stem}-{sha1(text.encode('utf-8'))[:width]}{ext}"
                if cand not in taken and cand not in originals:
                    rel = cand
                    break
            else:  # pragma: no cover - would need four pages with identical prefixes
                cand = f"{stem}-{sha1(text.encode('utf-8'))[:16]}{ext}"
                rel = cand
        taken[rel] = text
        out.append((rel, text))
    return out


def _write(out_dir: str, rel: str, text: str) -> int:
    """Write ``text`` to ``rel`` if it changed. Returns 1 when the file was rewritten.

    CRLF is normalised to LF first: prompts and tool output keep the CRLF they came with,
    and a page holding a stray ``\\r\\n`` would look "changed" on every single rebuild
    (the read side applies universal newlines, the write side must match it).
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    path = os.path.join(out_dir, rel)
    ensure_dir(os.path.dirname(path))
    try:
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                return 0
    except (OSError, UnicodeDecodeError):
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return 1


def _prune(out_dir: str, keep: Set[str]) -> int:
    """Delete stale generated pages — and only those."""
    removed = 0
    for dirpath, _dirnames, filenames in os.walk(out_dir):
        for fn in filenames:
            if not fn.endswith(".md"):
                continue
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, out_dir).replace("\\", "/")
            if rel in keep:
                continue
            try:
                with open(path, "r", encoding="utf-8", errors="replace") as fh:
                    head = fh.read(4096)
                    fh.seek(0)
                    body = fh.read()
            except OSError:
                continue
            if GENERATED_MARK in body or GENERATED_MARK in head:
                os.remove(path)
                removed += 1
    return removed


# ------------------------------------------------------------------ build

def build(
    out_dir: str,
    roots: Optional[Sequence[Tuple[str, str]]] = None,
    only: Optional[str] = None,
    min_turns: int = 1,
    since_days: Optional[int] = None,
    title: str = DEFAULT_TITLE,
    source_label: str = DEFAULT_SOURCE,
    tag_prefix: str = DEFAULT_PREFIX,
    split_threshold: int = 12,
    dry_run: bool = False,
    quiet: bool = False,
    verbose: bool = False,
    full: bool = False,
) -> dict:
    started = time.time()
    pairs = scan(roots, only)
    cache: Optional[Cache] = Cache(out_dir).load()
    if full:
        cache.clear()
    if dry_run:
        cache.read_only = True
    if not quiet:
        print(f"发现 {len(pairs)} 个会话存档，开始解析…", flush=True)
    sessions, problems = load_all(pairs, quiet=quiet, cache=cache, verbose=verbose)

    # filters
    kept: Dict[str, Session] = {}
    for sid, s in sessions.items():
        if len(s.turns) < min_turns:
            continue
        if since_days and s.started_at and not within_days(s.started_at, since_days):
            continue
        kept[sid] = s

    settle_titles(kept)
    number_duplicate_titles(kept)

    factsmap: Dict[str, SessionFacts] = {sid: analyze(s) for sid, s in kept.items()}
    projects = group_projects(kept, factsmap, split_threshold=split_threshold)
    topics = group_topics(kept, factsmap)

    facts_topic = topics
    topics_by_session: Dict[str, List] = {}
    for t in topics:
        for sid in t.sessions:
            topics_by_session.setdefault(sid, []).append(t)
    proj_of = {}
    for p in projects:
        for sid in p.sessions:
            proj_of[sid] = p

    pages: List[Tuple[str, str]] = []
    pages.append((f"{INDEX_NAME}.md", render_index(kept, projects, topics, source_label, tag_prefix, title)))
    pages.append(
        (
            f"{GUIDE_NAME}.md",
            render_guide(title, source_label, tag_prefix, [(n, r) for n, r in (roots or all_default_roots())]),
        )
    )
    for p in projects:
        rel = f"{DIR_PROJECT}/{p.name}.md"
        related = [t for t in facts_topic if set(t.sessions) & set(p.sessions)]
        related.sort(key=lambda t: -len(set(t.sessions) & set(p.sessions)))
        pages.append((rel, render_project(p, kept, factsmap, related[:12], source_label, tag_prefix)))
    for sid, s in kept.items():
        rel = f"{DIR_SESSION}/{session_page_name(s)}.md"
        pages.append(
            (rel, render_session(s, factsmap.get(sid), proj_of.get(sid), topics_by_session.get(sid, []),
                                 source_label, tag_prefix))
        )
    for t in topics:
        rel = f"{DIR_TOPIC}/{topic_page_name(t)}.md"
        pages.append((rel, render_topic(t, kept, source_label, tag_prefix)))
    pages.append((f"{DIR_ARCHIVE}/README.md", render_archive_note(source_label, tag_prefix, kept)))
    pages = _uniq_page_names(pages)

    written = 0
    if not dry_run:
        ensure_dir(out_dir)
        keep = {rel for rel, _ in pages}
        for rel, text in pages:
            written += _write(out_dir, rel, text)
        pruned = _prune(out_dir, keep)
    else:
        pruned = 0
    if cache is not None:
        cache.save()
    ok = bool(kept)
    if not ok and not quiet:
        print("注意：没有解析出任何可用的会话 —— 检查 --root 是否指向了存档目录。", flush=True)

    return {
        "ok": ok,
        "files": len(pairs),
        "sessions": len(kept),
        "skipped": len(sessions) - len(kept),
        "projects": len(projects),
        "topics": len(topics),
        "pages": len(pages),
        "written": written,
        "pruned": pruned,
        "reused": cache.reused,
        "parsed": cache.parsed,
        "full": full,
        "out": out_dir,
        "seconds": round(time.time() - started, 2),
        "problems": problems[:20],
        "project_names": [p.name for p in projects],
        "topic_titles": [t.title for t in topics[:20]],
    }
